"""Fit on public development labels and export a self-contained C++ model."""
import csv
import json

from architecture import DEFAULT_ARCH, ROOT
from experiment_displacement import DATA, train
from experiment_gap_features import read_rows, geometry_features, fit_corrections


def floats(values):
    return ','.join(format(float(value), '.17g') for value in values)


def main():
    rows = read_rows(DATA / 'development.golden.csv')
    gaps = json.loads((DEFAULT_ARCH / 'SRB_Gap.json').read_text())['Gap']
    model = train([row[0] for row in rows], 8, 16)
    features = [geometry_features(row, gaps) for row in rows]
    correction = fit_corrections(rows, model, features, 1000)
    ports = json.loads((DEFAULT_ARCH / 'SRB_Port.json').read_text())['Port']
    port_names = [port['Name'] for port in ports]
    intercept, ax, ay, source, target, table = model
    values = [0.0] * (3*3*15*35)
    for (sx, sy, bx, by), value in table.items():
        values[(((sx+1)*3+(sy+1))*15+bx)*35+by] = value
    line = [0.0] * (max(g['id'] for g in gaps['Line'])+1)
    block = [0.0] * (max(g['id'] for g in gaps['Block'])+1)
    for (kind, identifier), value in correction.items():
        (line if kind == 'line' else block)[identifier] = value
    content = '\n'.join([
        '// Generated by scripts/export_lookup.py from the fixed development partition.',
        '// Public labels are used only during this offline fitting step.',
        '#pragma once',
        '#include <array>',
        'namespace lookup_model {',
        f'constexpr double intercept={intercept:.17g}, ax={ax:.17g}, ay={ay:.17g};',
        f'constexpr std::array<double,{len(port_names)}> source={{{floats(source.get(p,0) for p in port_names)}}};',
        f'constexpr std::array<double,{len(port_names)}> target={{{floats(target.get(p,0) for p in port_names)}}};',
        f'constexpr std::array<double,{len(values)}> residual={{{floats(values)}}};',
        f'constexpr std::array<double,{len(line)}> line={{{floats(line)}}};',
        f'constexpr std::array<double,{len(block)}> block={{{floats(block)}}};',
        '} // namespace lookup_model',
        ''
    ])
    path = ROOT / 'src/lookup_model.hpp'
    path.write_text(content)
    print(json.dumps({'path': str(path), 'bytes': path.stat().st_size,
                      'development_rows': len(rows), 'residual_entries': len(table),
                      'geometry_entries': len(correction)}))


if __name__ == '__main__':
    main()
