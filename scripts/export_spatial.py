"""Export 795 spatial residual coefficients fitted from development predictions."""
import json

from architecture import ROOT
from experiment_spatial_residual import fit, load


def main():
    rows=load('development')
    families=('x_pair','y_pair')
    x_table,y_table=fit(rows,families,100)
    x_values=[0.0]*(12*12*3)
    y_values=[0.0]*(11*11*3)
    for (sx,tx,sign),value in x_table.items():
        x_values[(sx*12+tx)*3+sign+1]=value
    for (sy,ty,sign),value in y_table.items():
        y_values[(sy*11+ty)*3+sign+1]=value
    def values(data): return ','.join(format(value,'.17g') for value in data)
    output='\n'.join([
        '// Generated by scripts/export_spatial.py from development predictions.',
        '// Re-run development.approximate.csv with the base lookup model before regenerating.',
        '#pragma once','#include <array>','namespace spatial_model {',
        f'constexpr std::array<double,{len(x_values)}> x_pair={{{values(x_values)}}};',
        f'constexpr std::array<double,{len(y_values)}> y_pair={{{values(y_values)}}};',
        '} // namespace spatial_model',''])
    path=ROOT/'src/spatial_model.hpp'
    path.write_text(output)
    print(json.dumps({'path':str(path),'bytes':path.stat().st_size,
                      'x_entries':len(x_table),'y_entries':len(y_table)}))


if __name__=='__main__':main()
